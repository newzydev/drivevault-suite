<#
  Writes src\ai\EmbeddedKey.h: the NVIDIA API key of the online models, scrambled (NOT secure: see below).

  Usage (the key comes from the environment, so it is never in this file or in a command history of the repo):
      $env:DV_NVIDIA_KEY = 'nvapi-...'
      .\scripts\make-embedded-key.ps1

  The owner decided on 2026-11-19 that the program carries the key so that users need no key of their own. A key inside a program is only hidden from
  a casual look at the file: the program has to send it to NVIDIA, so anyone who studies the program or its network traffic can read it. If the key is
  abused: revoke it at build.nvidia.com, make a new one, run this script again and release a new version.
  The scrambling must match AiService.cpp (embeddedNvidiaKey): mask = SHA-256(salt + counter) blocks, counter 0, 1, 2 ...; cipher = key XOR mask.
#>
param([string]$OutFile = (Join-Path $PSScriptRoot '..\src\ai\EmbeddedKey.h'))

$ErrorActionPreference = 'Stop'
$plain = $env:DV_NVIDIA_KEY
if (-not $plain -or $plain -notmatch '^nvapi-[A-Za-z0-9_\-]{30,120}$') {
    throw 'Set $env:DV_NVIDIA_KEY to the NVIDIA API key (it starts with nvapi-).'
}
$salt = 'DriveVault.MasterPro.online-models.v1'
$key = [Text.Encoding]::ASCII.GetBytes($plain)
$sha = [Security.Cryptography.SHA256]::Create()
$mask = New-Object System.Collections.Generic.List[byte]
$counter = 0
while ($mask.Count -lt $key.Length) {
    $mask.AddRange($sha.ComputeHash([Text.Encoding]::ASCII.GetBytes($salt + $counter)))
    $counter++
}
$cipher = for ($i = 0; $i -lt $key.Length; $i++) { $key[$i] -bxor $mask[$i] }
$rows = for ($i = 0; $i -lt $cipher.Count; $i += 12) {
    '    ' + ((($cipher[$i..([Math]::Min($i + 11, $cipher.Count - 1))]) | ForEach-Object { '0x{0:x2}' -f $_ }) -join ', ') + ','
}
$saltLine = 'inline constexpr char kEmbeddedKeySalt[] = "' + $salt + '";'
$text = @()
$text += '// Generated by scripts\make-embedded-key.ps1 - do not edit by hand. The NVIDIA API key of the online models, scrambled (see that script: this hides the key'
$text += '// from a casual look only; it is not protection).'
$text += '#pragma once'
$text += ''
$text += 'namespace dm::ai {'
$text += $saltLine
$text += 'inline constexpr unsigned char kEmbeddedNvidiaKey[] = {'
$text += $rows
$text += '};'
$text += '} // namespace dm::ai'
$text += ''
[IO.File]::WriteAllText([IO.Path]::GetFullPath($OutFile), ($text -join "`r`n"), (New-Object Text.UTF8Encoding($false)))
"Wrote $OutFile ($($key.Length) bytes)"
