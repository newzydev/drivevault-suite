<#
.SYNOPSIS  Writes GoogleDesktopOAuth.h: the suite's Google "Desktop app" OAuth client, AES-256 encrypted, for shared\auth.
.DESCRIPTION
  The client id and secret are NOT in the repository. They are read from (first one that exists):
    $env:DV_GOOGLE_OAUTH_FILE, else a client_secret_*.json of Google ("installed" = Desktop app) in the folder above the repository,
    else GOOGLE_LOGIN_CLIENT_ID.txt there. The JSON wins because the txt can hold the pair of an older, different client
    (it gave redirect_uri_mismatch on 2026-11-20: only a Desktop client accepts the loopback address of the sign-in).
  The txt file has the lines GOOGLE_LOGIN_CLIENT_ID=... and GOOGLE_LOGIN_CLIENT_SECRET=...
  Without a file an EMPTY header is written (the program builds, and its Google sign-in says "not available").
  The key is stored next to the ciphertext in the program: this hides the pair from a casual look at the exe, it is not a secret store.
  The header is rewritten only when the source file changed (its SHA-256 is in the header), so the build is not redone for nothing.
.EXAMPLE   .\make-oauth-header.ps1 -Output build\release\generated\dv_account\GoogleDesktopOAuth.h
#>
param([Parameter(Mandatory)] [string]$Output, [string]$Source)

$ErrorActionPreference = 'Stop'
$suiteRoot = Split-Path -Parent (Split-Path -Parent $PSScriptRoot)
$above = Split-Path -Parent $suiteRoot

function Find-Source {
    if ($Source) { return $Source }
    if ($env:DV_GOOGLE_OAUTH_FILE) { return $env:DV_GOOGLE_OAUTH_FILE }
    # the JSON that Google gives for a "Desktop app" client comes first: the txt may also hold the pair of an older, different client
    $json = Get-ChildItem -LiteralPath $above -Filter 'client_secret_*.json' -File -ErrorAction SilentlyContinue | Select-Object -First 1
    if ($json) { return $json.FullName }
    $txt = Join-Path $above 'GOOGLE_LOGIN_CLIENT_ID.txt'
    if (Test-Path -LiteralPath $txt -PathType Leaf) { return $txt }
    return $null
}

function Write-Header([string]$key, [string]$iv, [string]$cipher, [string]$hash) {
    New-Item -ItemType Directory -Force -Path (Split-Path -Parent $Output) | Out-Null
    $text = @"
// Generated by shared\scripts\make-oauth-header.ps1 - do not edit, do not commit (build output).
// source-sha256: $hash
#pragma once
namespace dv::account::desktopOAuth {
inline constexpr char key[] = "$key";
inline constexpr char iv[] = "$iv";
inline constexpr char ciphertext[] = "$cipher";
}
"@
    [IO.File]::WriteAllText($Output, $text, (New-Object Text.UTF8Encoding($false)))
}

$path = Find-Source
if (-not $path) {
    if (-not (Test-Path -LiteralPath $Output)) { Write-Header '' '' '' 'none' }
    Write-Host "make-oauth-header: no Google OAuth file found - Google sign-in will say 'not available' in this build." -ForegroundColor Yellow
    exit 0
}
if (-not (Test-Path -LiteralPath $path -PathType Leaf)) { throw "The Google OAuth file does not exist: $path" }

$hash = (Get-FileHash -LiteralPath $path -Algorithm SHA256).Hash
if ((Test-Path -LiteralPath $Output) -and (Select-String -LiteralPath $Output -Pattern "source-sha256: $hash" -SimpleMatch -Quiet)) { exit 0 }

$id = $null; $secret = $null
if ($path -like '*.json') {
    $installed = (Get-Content -LiteralPath $path -Raw | ConvertFrom-Json).installed
    if (-not $installed) { throw 'The Google JSON file is not a "Desktop app" (installed) client.' }
    $id = $installed.client_id; $secret = $installed.client_secret
} else {
    foreach ($line in Get-Content -LiteralPath $path) {
        if ($line -match '^\s*GOOGLE_LOGIN_CLIENT_ID\s*=\s*(.+?)\s*$') { $id = $Matches[1].Trim([char]34, [char]39) }
        if ($line -match '^\s*GOOGLE_LOGIN_CLIENT_SECRET\s*=\s*(.+?)\s*$') { $secret = $Matches[1].Trim([char]34, [char]39) }
    }
}
if ($id -notmatch '^[A-Za-z0-9_-]+\.apps\.googleusercontent\.com$' -or $secret -notmatch '^[A-Za-z0-9_-]+$') {
    throw 'The Google OAuth file does not hold a valid client id and secret.'
}

$aes = [Security.Cryptography.Aes]::Create()
try {
    $aes.KeySize = 256
    $aes.GenerateKey(); $aes.GenerateIV()
    $plain = [Text.Encoding]::UTF8.GetBytes((@{ GOOGLE_LOGIN_CLIENT_ID = $id; GOOGLE_LOGIN_CLIENT_SECRET = $secret } | ConvertTo-Json -Compress))
    $encryptor = $aes.CreateEncryptor()
    try { $cipher = [Convert]::ToBase64String($encryptor.TransformFinalBlock($plain, 0, $plain.Length)) } finally { $encryptor.Dispose(); [Array]::Clear($plain, 0, $plain.Length) }
    Write-Header ([Convert]::ToBase64String($aes.Key)) ([Convert]::ToBase64String($aes.IV)) $cipher $hash
} finally { $aes.Dispose() }
Write-Host 'make-oauth-header: Google OAuth client embedded (encrypted).'
